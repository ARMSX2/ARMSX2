// VIF unpack differential tests — arm64 NEON unpackers vs the scalar oracle.
//
// The VIF UNPACK command streams packed vertex data from the VIF FIFO into VU
// memory, expanding it to quadwords on the way and optionally masking, offsetting
// or skipping individual lanes. Two NEON code generators implement it on arm64,
// and until now neither had any test coverage at all:
//
//   VifUnpackNEON_Dynarec (Vif_Dynarec.cpp)  — the fast path. Compiles one
//       routine per (format, mask, mode, cycle) combination with the whole
//       num-loop unrolled inside it. Reached via dVifUnpack<idx>().
//   VifUnpackNEON_Simple  (Vif_UnpackNEON.cpp) — the per-cycle callees the
//       "interpreter" path dispatches through. Reached via _nVifUnpack(), and
//       generated by VifUnpackSSE_Init().
//
// Note that _nVifUnpack is only nominally an interpreter on arm64: for mode 0 it
// calls the NEON routines above, so using it as the oracle would compare our own
// codegen against our own codegen. The real oracle here is VIFfuncTable
// (Vif_Unpack.cpp) — the UNPACK_S / UNPACK_V2 / UNPACK_V4 / UNPACK_V4_5 template
// family. That is plain scalar C++, architecture-neutral, and shared verbatim
// with upstream PCSX2, so it is independent of everything under test.
// ReferenceUnpack below drives it with the same addressing _nVifUnpackLoop uses.
//
// ---------------------------------------------------------------------------
// The W lane of V2_32 and the V3_* formats is deliberately NOT compared.
//
// Both NEON generators zero the W lane in cases the scalar table does not:
// V2_32 does it when IsAligned, V3_32/V3_8 when UnpkLoopIteration != IsAligned,
// V3_16 on a qword boundary. The source calls this "tested on ps2", and the x86
// SSE generator does exactly the same thing (Vif_UnpackSSE.cpp), so it is an
// intentional accuracy refinement in the generators rather than a divergence we
// introduced. Meanwhile Vif_Unpack.cpp routes V3 through UNPACK_V4 on purpose —
// "confirmed real hardware behavior that games such as Ape Escape 3 depend on"
// — because the W field is normally overwritten by the following unpack anyway.
//
// Rather than re-derive the generators' iteration arithmetic in the test (which
// would make the assertion tautological), those formats compare X/Y/Z against
// the oracle and leave W to the dedicated AlignedV2_32 test below, which asserts
// the one W-lane fact that is independently checkable from the spec.
// X/Y/Z is where the sign-extension, lane-duplication and masking logic lives,
// so the formats are still meaningfully covered.

