// The one W-lane fact that is checkable without re-deriving the generators'
// iteration arithmetic: an aligned V2_32 unpack zeroes W. Both generators do it
// ("zero last word - tested on ps2"), and the x86 SSE generator agrees, so a
// NEON transcription that dropped the Ins(wzr) would be a real regression that
// the oracle comparison above deliberately cannot see.
TEST(VifUnpackAligned, AlignedV2_32ZeroesWLane)
{
	ASSERT_TRUE(recompiler_tests::RecompilerTestEnvironment::IsReady());
	EnsureVifUnpackReady();

	UnpackCase c{"aligned_v2_32", 1, V2_32, false, 0, 4, 1, 1, 0, 0, 0x000, /*start_aligned=*/1};
	const std::vector<u8> data = MakeSourceData(static_cast<size_t>(c.num) * nVifT[V2_32]);

	const RunResult dyn = RunPath(c, data, Path::Dynarec);

	const u32* qw = reinterpret_cast<const u32*>(dyn.mem.data());
	for (u32 i = 0; i < c.num; i++)
	{
		EXPECT_EQ(0u, qw[i * 4 + 3]) << "aligned V2_32 quadword " << i << " W lane should be zeroed";
		// X/Y must still carry data — guards against the whole write being lost.
		EXPECT_NE(0u, qw[i * 4 + 0] | qw[i * 4 + 1]) << "quadword " << i << " lost its data";
	}
}

// dVifUnpack falls back to _nVifUnpack when the write would run past the end of
// VU memory, rather than letting the compiled routine scribble out of bounds.
// The fallback is a plain branch, but it is the only thing standing between an
// oversized transfer and memory corruption, so it is worth pinning.
TEST(VifUnpackWrap, OversizedTransferFallsBackToInterpreter)
{
	ASSERT_TRUE(recompiler_tests::RecompilerTestEnvironment::IsReady());
	EnsureVifUnpackReady();

	// 64 quadwords starting 16 bytes from the end of VU1 memory: the block
	// length far exceeds what remains, so the bounds check must reject it.
	UnpackCase c{"wrap", 1, V4_32, false, 0, 64, 1, 1, 0, 0, 0x3FF0, 0};
	const std::vector<u8> data = MakeSourceData(static_cast<size_t>(c.num) * nVifT[V4_32]);

	const RunResult expected = RunPath(c, data, Path::Reference);
	const RunResult dyn = RunPath(c, data, Path::Dynarec);

	// Taking the fallback means the result is the interpreter's, which is what
	// the oracle models — including the address wrap back to the start.
	ExpectMemEqual(c, expected, dyn, "dynarec wrap fallback");
}

