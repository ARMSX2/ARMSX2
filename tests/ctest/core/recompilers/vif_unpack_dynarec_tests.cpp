// Generates the nVifUpk[] table that _nVifUnpack dispatches through. VMManager
// does this at startup; the recompiler harness does not, so every suite here has
// to make sure it has happened. Not just the suites that call _nVifUnpack
// directly: dVifUnpack falls back to it for out-of-bounds transfers, and a
// missing table shows up there as a call through a null pointer.
void EnsureVifUnpackReady()
{
	static bool ready = false;
	if (ready)
		return;
	VifUnpackSSE_Init();
	resetNewVif(0);
	resetNewVif(1);
	ready = true;
}

class VifUnpackTest : public ::testing::TestWithParam<UnpackCase>
{
protected:
	void SetUp() override
	{
		ASSERT_TRUE(recompiler_tests::RecompilerTestEnvironment::IsReady())
			<< "RecompilerTestEnvironment must be initialized by main()";
		EnsureVifUnpackReady();
	}
};

TEST_P(VifUnpackTest, NeonPathsMatchScalarOracle)
{
	const UnpackCase& c = GetParam();

	const u8 vSize = nVifT[MakeCmd(c.fmt, c.masked) & 0x0f];
	ASSERT_GT(vSize, 0) << "format has no source-size entry";
	const std::vector<u8> data = MakeSourceData(static_cast<size_t>(c.num) * vSize);

	const RunResult expected = RunPath(c, data, Path::Reference);
	const RunResult neon = RunPath(c, data, Path::InterpreterNeon);
	const RunResult dyn = RunPath(c, data, Path::Dynarec);

	ExpectMemEqual(c, expected, neon, "interpreter NEON (VifUnpackNEON_Simple)");
	ExpectMemEqual(c, expected, dyn, "dynarec (VifUnpackNEON_Dynarec)");

	// MODE 2 and 3 write the row register back; 0 and 1 must leave it alone.
	// Checked for every case so an unintended write-back is caught too.
	for (int i = 0; i < 4; i++)
	{
		EXPECT_EQ(expected.row._u32[i], dyn.row._u32[i])
			<< "dynarec MaskRow lane " << i << " after mode " << c.mode;
	}
}

