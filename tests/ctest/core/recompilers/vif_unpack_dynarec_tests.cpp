// UNPACK command bytes are 0b0110_0000 | (vn << 2) | vl, with bit 4 (0x10)
// selecting the masked variant. These are the vn/vl halves; MakeCmd adds the
// 0x60 base and the mask bit.
enum UpkFormat : u8
{
	S_32  = 0x00, S_16  = 0x01, S_8  = 0x02,
	V2_32 = 0x04, V2_16 = 0x05, V2_8 = 0x06,
	V3_32 = 0x08, V3_16 = 0x09, V3_8 = 0x0a,
	V4_32 = 0x0c, V4_16 = 0x0d, V4_8 = 0x0e, V4_5 = 0x0f,
};

constexpr u8 MakeCmd(UpkFormat fmt, bool masked)
{
	return static_cast<u8>(0x60 | fmt | (masked ? 0x10 : 0x00));
}

// The generators zero W for these; the scalar table does not. See header.
constexpr bool HasDivergentWLane(UpkFormat fmt)
{
	return fmt == V2_32 || fmt == V3_32 || fmt == V3_16 || fmt == V3_8;
}

constexpr u32 VuMemSize(int idx) { return idx ? 0x4000u : 0x1000u; }

u8* VuMem(int idx) { return reinterpret_cast<u8*>(vuRegs[idx].Mem); }

// Mirrors the static getVUptr in Vif_Unpack.cpp.
u32* VuPtr(int idx, u32 offset)
{
	return reinterpret_cast<u32*>(VuMem(idx) + (offset & (idx ? 0x3ff0 : 0xff0)));
}

vifStruct& Vif(int idx) { return idx ? vif1 : vif0; }
VIFregisters& VifRegs(int idx) { return idx ? vif1Regs : vif0Regs; }

// A non-zero, non-repeating fill so that lanes the unpack is supposed to leave
// alone (write-protect masks, skipped cycles) are distinguishable from lanes it
// zeroed or wrote. A zero fill would hide exactly those bugs.
void FillVuMemPattern(int idx)
{
	u8* mem = VuMem(idx);
	const u32 size = VuMemSize(idx);
	for (u32 i = 0; i < size; i += 4)
	{
		const u32 word = 0xA5A50000u ^ (i * 2654435761u);
		std::memcpy(mem + i, &word, sizeof(word));
	}
}

struct UnpackCase
{
	const char* name;
	int idx;             // 0 = VIF0 (4 KB VU mem), 1 = VIF1 (16 KB)
	UpkFormat fmt;
	bool masked;
	u8 usn;              // unsigned flag; only meaningful for the 8/16-bit formats
	u32 num;             // quadwords to write (1..256)
	u8 cl, wl;           // CYCLE register: cl < wl fills, cl > wl skips
	u32 mode;            // MODE register: 0 normal, 1 offset, 2 difference, 3 set-row
	u32 mask;            // MASK register: 2 bits per lane per cycle
	u32 addr;            // tag.addr, the VU-memory write cursor
	u8 start_aligned;
};

// Row/col seeds. Distinct, non-zero and not equal to each other so a test can
// tell "took the row" from "took the col" from "kept the data".
constexpr u32 kRow[4] = {0x11111111u, 0x22222222u, 0x33333333u, 0x44444444u};
constexpr u32 kCol[4] = {0x55555555u, 0x66666666u, 0x77777777u, 0x78888888u};

void SeedVifState(const UnpackCase& c)
{
	vifStruct& vif = Vif(c.idx);
	VIFregisters& regs = VifRegs(c.idx);

	vif.cmd = MakeCmd(c.fmt, c.masked);
	vif.usn = c.usn;
	vif.cl = 0; // _nVifUnpackLoop asserts this
	vif.tag.addr = c.addr;
	vif.start_aligned = c.start_aligned;

	for (int i = 0; i < 4; i++)
	{
		vif.MaskRow._u32[i] = kRow[i];
		vif.MaskCol._u32[i] = kCol[i];
	}

	regs.num = c.num;
	regs.cycle.cl = c.cl;
	regs.cycle.wl = c.wl;
	regs.mode = c.mode;
	regs.mask = c.mask;

	// Guest-visible row/col mirrors. The unpack paths read vif.MaskRow/MaskCol
	// rather than these, but keep them consistent so the state is realistic.
	regs.r0 = kRow[0]; regs.r1 = kRow[1]; regs.r2 = kRow[2]; regs.r3 = kRow[3];
	regs.c0 = kCol[0]; regs.c1 = kCol[1]; regs.c2 = kCol[2]; regs.c3 = kCol[3];
}

// isFill as nVifUnpack computes it before dispatching (Vif_Unpack.cpp).
bool ComputeIsFill(const UnpackCase& c)
{
	const uint wl = c.wl ? c.wl : 256;
	return c.cl < wl;
}

// The oracle: _nVifUnpackLoop's addressing, always dispatching through the
// scalar VIFfuncTable instead of the NEON per-cycle callees.
void ReferenceUnpack(const UnpackCase& c, const u8* data)
{
	vifStruct& vif = Vif(c.idx);
	VIFregisters& regs = VifRegs(c.idx);

	const bool isFill = ComputeIsFill(c);
	const int usn = !!vif.usn;
	const int upkNum = vif.cmd & 0x1f;
	const u8 vSize = nVifT[upkNum & 0x0f];
	const int skipSize = (regs.cycle.cl - regs.cycle.wl) * 16;

	// _nVifUnpackLoop indexes [idx][doMode ? mode : 0][...]; with doMode being
	// !!mode that is just mode.
	const UNPACKFUNCTYPE ft = VIFfuncTable[c.idx][regs.mode & 3][(usn * 2 * 16) + upkNum];

	do
	{
		ft(VuPtr(c.idx, vif.tag.addr), data);

		vif.tag.addr += 16;
		--regs.num;
		++vif.cl;

		if (isFill)
		{
			if (vif.cl <= regs.cycle.cl)
				data += vSize;
			else if (vif.cl == regs.cycle.wl)
				vif.cl = 0;
		}
		else
		{
			data += vSize;
			if (vif.cl >= regs.cycle.wl)
			{
				vif.tag.addr += skipSize;
				vif.cl = 0;
			}
		}
	} while (regs.num);
}

// Deterministic source bytes. Values are spread across the full range so that
// sign-extension bugs in the 8/16-bit formats change the result.
std::vector<u8> MakeSourceData(size_t bytes)
{
	std::vector<u8> data(bytes + 64, 0); // slack: V3 reads can overrun the last element
	for (size_t i = 0; i < data.size(); i++)
		data[i] = static_cast<u8>((i * 37) ^ 0x8Cu);
	return data;
}

struct RunResult
{
	std::vector<u8> mem;
	u128 row;
};

enum class Path { Reference, InterpreterNeon, Dynarec };

RunResult RunPath(const UnpackCase& c, const std::vector<u8>& data, Path path)
{
	FillVuMemPattern(c.idx);
	SeedVifState(c);

	const bool isFill = ComputeIsFill(c);
	switch (path)
	{
		case Path::Reference:
			ReferenceUnpack(c, data.data());
			break;
		case Path::InterpreterNeon:
			_nVifUnpack(c.idx, data.data(), VifRegs(c.idx).mode, isFill);
			break;
		case Path::Dynarec:
			// Recompile from scratch so each case exercises dVifCompile rather
			// than inheriting a block another case happened to key-match.
			//
			// resetNewVif, not dVifReset: only the former assigns nVif[idx].idx,
			// and VifUnpackNEON_Dynarec::SetMasks/writeBackRow resolve MTVU_VifX
			// through it. Left at its zero-initialized value, a VIF1 unpack reads
			// VIF0's row/col registers.
			resetNewVif(c.idx);
			if (c.idx)
				dVifUnpack<1>(data.data(), isFill);
			else
				dVifUnpack<0>(data.data(), isFill);
			break;
	}

	RunResult out;
	out.mem.resize(VuMemSize(c.idx));
	std::memcpy(out.mem.data(), VuMem(c.idx), out.mem.size());
	out.row = Vif(c.idx).MaskRow;
	return out;
}

// Compares VU memory word by word, skipping the W word of every quadword when
// the format's W lane is intentionally divergent (see header).
void ExpectMemEqual(const UnpackCase& c, const RunResult& expected, const RunResult& actual, const char* what)
{
	ASSERT_EQ(expected.mem.size(), actual.mem.size());
	const bool skip_w = HasDivergentWLane(c.fmt);

	const u32* e = reinterpret_cast<const u32*>(expected.mem.data());
	const u32* a = reinterpret_cast<const u32*>(actual.mem.data());
	const size_t words = expected.mem.size() / 4;

	int reported = 0;
	for (size_t i = 0; i < words; i++)
	{
		if (skip_w && (i & 3) == 3)
			continue;
		if (e[i] == a[i])
			continue;
		if (++reported > 8)
		{
			ADD_FAILURE() << what << ": more divergent words beyond the first 8";
			return;
		}
		ADD_FAILURE() << what << ": VU" << c.idx << " mem word " << i
					  << " (qw " << (i / 4) << " lane " << "XYZW"[i & 3] << ")"
					  << " expected 0x" << std::hex << e[i] << " got 0x" << a[i] << std::dec;
	}
}

